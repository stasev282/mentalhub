/**
 * Модель данных прототипа.
 *
 * Файл написан так, как читалась бы схема будущей базы данных:
 * каждая сущность — отдельная таблица, связи — через *Id-поля.
 * Никаких вычисляемых полей здесь нет и не должно появляться —
 * если понадобится "разница", "среднее" или "тренд", это признак
 * того, что решение принимается не в коде прототипа.
 */

/**
 * Одна оценка одной эмоции в один момент времени.
 *
 * Это НЕ пара "до/после" в одной записи. Пациент может отметить
 * несколько эмоций за один thought record, и каждая оценивается
 * отдельно на шаге 2 (phase: "before") и отдельно на шаге 7
 * (phase: "after"). Если пациент не вернулся к шагу 7 — строки с
 * phase: "after" для этой эмоции в массиве просто нет. Это valid
 * состояние данных, а не пропуск, который нужно чем-то заполнять.
 */
export type MoodRating = {
  label: string; // название эмоции в свободной форме, например "Тревога", "Стыд"
  phase: "before" | "after";
  intensity: number; // 0–100, самооценка пациента
};

/**
 * Запись дневника мыслей (thought record, форма Гринбергера и Падески).
 * Столбцы 1–7 соответствуют полям situation … moods(after).
 */
export type ThoughtRecord = {
  id: string;
  patientId: string;
  createdAt: string; // ISO 8601
  situation: string; // столбец 1: кто, где, когда, что происходило
  moods: MoodRating[]; // столбцы 2 и 7: эмоции и их сила до/после
  automaticThought: string; // столбец 3
  evidenceFor: string; // столбец 4
  evidenceAgainst: string; // столбец 5
  balancedThought: string; // столбец 6
  distortions: string[]; // когнитивные искажения — ставит терапевт, не пациент
};

/**
 * Ежедневная быстрая отметка тревоги с главного экрана пациента.
 * Строка существует на каждый день курса; anxiety остаётся null,
 * пока пациент не заполнил отметку за этот день — это не то же
 * самое, что значение 0.
 */
export type DailyCheckin = {
  patientId: string;
  date: string; // ISO 8601, дата без времени
  anxiety: number | null; // 0–100
};

/**
 * Ответ на опросник GAD-7 за неделю курса.
 * total остаётся null, пока опросник не пройден на этой неделе.
 * Пороговые значения и интерпретация намеренно не хранятся и не
 * выводятся — только сырая сумма баллов (0–21).
 */
export type Gad7Response = {
  patientId: string;
  weekOfCourse: number;
  total: number | null; // 0–21
};

/**
 * Домашнее задание пациента. progressLabel — фактическая строка
 * ("6 из 7", "31 за 7 дней"), а не статус выполнения — вердиктов
 * "выполнено/нарушено" в модели данных нет.
 */
export type HomeworkItem = {
  patientId: string;
  title: string;
  progressLabel: string;
};

export type Patient = {
  id: string;
  displayName: string;
  age: number;
  focus: string; // фокус работы, например "Социальная тревога"
  weekOfCourse: number;
  totalWeeks: number;
  nextSession: string; // ISO 8601
  recordsTotal: number; // всего thought records за весь курс, показанных на экране может быть меньше
};

